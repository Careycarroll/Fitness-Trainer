function dateAsSeed(dateStr) {
  const num = Number(String(dateStr ?? '').replace(/-/g, ''));
  return Number.isFinite(num) && num > 0 ? num : 20261123;
}

function weekdayOf(dateStr) {
  const parts = String(dateStr ?? '').split('-').map(Number);
  const [y, m, d] = parts.length === 3 ? parts : [2026, 11, 23];
  const date = new Date(y, (m || 1) - 1, d || 1, 12, 0, 0);
  const dayNames = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];
  return dayNames[date.getDay()] ?? 'mon';
}

