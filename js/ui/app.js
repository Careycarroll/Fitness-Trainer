function paintStatus() {
  // Live rows only. A superseded row is history, not the current answer, and
  // showing both would read as two conflicting maxes for one lift.
  if (maxListEl) {
    const live = (persisted?.exerciseMax ?? []).filter((r) => r.supersededAt == null);
    maxListEl.textContent = live.length
      ? live
          .slice()
          .sort((a, b) => (a.exerciseId < b.exerciseId ? -1 : 1))
          .map((r) => `${r.exerciseId}: ${r.e1rm} lb (${r.source}, ${r.effectiveDate})`)
          .join(' | ')
      : 'No maxes entered yet.';
  }

  const rows = persisted?.importedSets?.length ?? 0;

  // Rebuilt from stored rows on load, so the queue survives a reload rather
  // than existing only in the session that imported. NOT conditional on the
  // export button: this block used to sit inside `if (csvBtn)`, so a markup
  // change that dropped #export-csv would have silently stopped unmapped sets
  // being reviewable (#57). The review queue has nothing to do with CSV export.
  if (!importReview.length && rows) {
    importReview = buildReviewQueue(persisted.importedSets);
  }

  // Nothing to export until the FitNotes import lands (#24), so the button is
  // disabled rather than left clickable and immediately apologetic. A control
  // that cannot succeed in the current state reads as a defect.
  const csvBtn = document.querySelector('#export-csv');
  if (csvBtn) {
    csvBtn.disabled = rows === 0;
    csvBtn.title = rows === 0
      ? 'No imported history yet \u2014 available after a FitNotes import (#24)'
      : `Export ${rows} imported sets as CSV`;
  }

  paintReview();
  // Imported history changes which dates clash, so the preview follows it.
  paintDates();

  if (!statusEl) return;
  const last = persisted?.meta?.lastImportAt;
  const parts = [];
  if (storageNote) parts.push(storageNote);
  parts.push(last
    ? `Last FitNotes import: ${last.slice(0, 10)}.`
    : 'No FitNotes history imported yet.');
  statusEl.textContent = parts.join(' ');
}

/**
 * What the generator could not honour about the REQUEST — #51.
 *
 * Read straight off the program rather than held in module state: `storageNote`
 * is cleared on every successful save, which would take this with it, and a
 * second copy of the rule in the UI is how two copies drift apart. The engine
 * decided this; the UI only phrases it.
 *
 * Same honesty mechanism as the omission report in #43: name the real cause.
 * "You asked for 7 and got 6" without "no 7-session split template exists"
 * reads as a bug in the app rather than a limit of the catalog, and the athlete
 * cannot act on it.
 *
 * Deliberately not the word "reduced". Only one conditioning split exists, so a
 * 1-session HIIT request resolves UPWARD to 3 — being handed two sessions you
 * did not ask for is a recovery and time claim you never made, and it needs
 * saying just as much.
 */
/**
 * Why this split, when the style did not ask for it — #76.
 *
 * `chooseSplit()` has an exit path that matches on DAY COUNT ALONE:
 *
 *     const exact = usable.find((s) => s.daysPerWeek === daysPerWeek);
 *     if (exact) return { split: exact, sessionMismatch: null };
 *
 * The session count was honoured, so nothing was reported — but the style may
 * never have listed this split. `ppl-6` is the only 6-day template in the
 * catalog, so core, strength and powerlifting all land on a hypertrophy split
 * at 6 days, and athletic lands on a split it does not list at four separate
 * day counts. Eight of thirty combinations, all silent until now.
 *
 * The split is NOT changed — there is one template per day count, so refusing
 * it would fall through to the nearest count and hand athletic at 1 day a 4-day
 * split. This states the gap instead, which is the same move #51 made for
 * session count.
 *
 * `defs` is needed for the split's display name; the id is the fallback rather
 * than a throw, because this runs inside a render path.
 */
export function splitNoticeHtml(program, defs) {
  const fit = program?.splitFit;
  if (!fit) return '';

  const nameOf = (id) =>
    (defs?.splits ?? []).find((s) => s.id === id)?.name ?? id;

  const parts = [];

  if (!fit.preferred) {
    const prefers = (fit.prefers ?? []).map(nameOf);
    parts.push(
      `This style does not list ${esc(nameOf(fit.splitId))} among the splits it ` +
      `was designed around.` +
      (prefers.length ? ` It prefers: ${esc(prefers.join(', '))}.` : '')
    );
  }

  const weak = fit.weakDays ?? [];
  if (weak.length) {
    const labels = weak.map((d) => d.label).join(', ');
    parts.push(
      `${weak.length} of the ${fit.totalDays} days in ` +
      `${esc(nameOf(fit.splitId))} — ${esc(labels)} — train nothing this style ` +
      `focuses on.`
    );
  }

  if (!parts.length) return '';
  return `<p class="request-note" role="status">${parts.join(' ')}</p>`;
}

export function sessionNoticeHtml(program) {
  const mm = program?.sessionMismatch;
  if (!mm) return '';
  const verb = mm.resolved > mm.requested ? 'has' : 'has only';
  return `<p class="request-note" role="status">You asked for ${mm.requested}
    ${mm.requested === 1 ? 'session' : 'sessions'} a week; this program ${verb}
    ${mm.resolved}, because ${esc(mm.reason)}. Available for this style:
    ${mm.available.join(', ')}.</p>`;
}

function paint(out) {
  if (!current) return;
  const targetEl = (activeMode === 'wod' ? document.querySelector('#wod-out') : document.querySelector('#out')) || out;
  if (targetEl) out = targetEl;
  // ONE save anchor. Every mutation path - assignment, splice, swap, remove,
  // regenerate - mutates `current` and then calls paint(out), so hooking here
  // covers all of them. Four call sites would be four chances to miss one.
  scheduleSave();
  const style = currentDefs.styles.find((s) => s.id === current.styleId);
  const styleName = style?.name ?? current.styleId;
  const displayName = current.name ? `${current.name} · ${styleName}` : styleName;
  const seedText = seedLabel || String(current.seed);
  const seedTitle = seedLabel
    ? `Named seed “${esc(seedLabel)}” resolves to ${current.seed}`
    : `Resolved seed ${current.seed}`;
  const isCrossfitPreset = current?.styleId === 'crossfit' && String(current?.id || '').startsWith('preset-');
  const editMessage = isCrossfitPreset
    ? '<p class="edit-note">Prescribed CrossFit benchmark — tap <strong>Import to Logger</strong> (or Start Workout) to log your score.</p>'
    : edited
      ? '<p class="edit-note">This draft has local edits, saved automatically. Regenerating replaces them.</p>'
      : '<p class="edit-note">Sets and reps are editable; draft edits remain only on this screen. Intensity is prescribed as a percentage of 1RM — absolute loads need logged maxes (M7).</p>';

  const isWodView = activeMode === 'wod' || (scope === 'session' && current.weeks.length === 1 && current.weeks[0].sessions.length === 1 && (current.name || currentRequest?.benchmarkId || currentRequest?.styleId === 'hiit'));

  const metaText = isWodView
    ? `Workout of the Day · ${current.schedule?.[0] ? current.schedule[0].toUpperCase() : 'Today'} · seed <button class="ghost seed-copy" data-copy-seed="${esc(String(current.seed))}" title="${seedTitle}">${esc(seedText)}</button>${seedLabel && !seedLabel.startsWith('WOD') ? ` <span class="resolved-seed">(resolved: ${current.seed})</span>` : ''}`
    : `${scope === 'session' ? `${(current.weeks[0]?.sessions.length ?? 0)} split days · session preview` : `${current.weeks.length} weeks × ${(current.weeks[0]?.sessions.length ?? 0)} days`} · seed <button class="ghost seed-copy" data-copy-seed="${esc(String(current.seed))}" title="${seedTitle}">${esc(seedText)}</button>${seedLabel ? ` <span class="resolved-seed">(resolved: ${current.seed})</span>` : ''}`;

  const head = `
    <div class="program-head">
      <h2>${esc(displayName)}</h2>
      ${current.description ? `<p class="benchmark-desc">${esc(current.description)}</p>` : ''}
      <p class="meta">
        ${metaText}
      </p>
      ${sessionNoticeHtml(current)}
      ${splitNoticeHtml(current, currentDefs)}
      ${editMessage}
    </div>`;

  if (isWodView) {
    const session = current.weeks[0].sessions[0];
    out.innerHTML = head + renderSession(session, 0, 0, style);
    return;
  }

  if (scope === 'session') {
    const sessions = current.weeks[0].sessions;
    visibleDay = Math.min(visibleDay, Math.max(0, sessions.length - 1));
    const tabs = `
      <nav class="day-picker" aria-label="Split day preview">
        ${sessions.map((s, i) => `
          <button class="ghost day-tab${i === visibleDay ? ' selected' : ''}"
                  data-day="${i}" aria-pressed="${i === visibleDay}">
            ${esc(s.label)}
          </button>`).join('')}
      </nav>`;
    const context = `<p class="note">Day ${visibleDay + 1} of a ${sessions.length}-day week. Switch to All weeks to see the whole block.</p>`;
    // Volume is a WEEK-level fact, so it is shown once above the day tabs rather
    // than repeated per day. A single day cannot be over MRV for the week.
    out.innerHTML = head + renderVolume(current.weeks[0].volume) + tabs + context
      + renderSession(sessions[visibleDay], 0, visibleDay, style);
    return;
  }

  out.innerHTML = head + current.weeks.map((week, w) => `
    <h2 class="week">Week ${week.week}</h2>
    ${renderVolume(week.volume)}
    ${week.sessions.map((session, s) => renderSession(session, w, s, style)).join('')}
  `).join('');
}

export function renderSession(session, w, s, style) {
  const groups = allSetGroups(session);
  const allowSwap = session?.styleId !== 'crossfit';
  const domainMeta = session.domain === 'load'
    ? `${session.fatigueUsed ?? groups.reduce((n, g) => n + (g.fatigueCost ?? 0), 0)} / ${session.fatigueBudget ?? style.fatigueBudget} fatigue`
    : sessionTiming(session);
  const timing = '';

  return `
    <article class="card session">
      <div class="session-card-head" style="display:flex; justify-content:space-between; align-items:center; gap:8px; flex-wrap:wrap;">
        <h3 style="margin:0;"><span class="day-index">Day ${s + 1}</span>${esc(session.label)}</h3>
        <button type="button" class="primary" data-start-w="${w}" data-start-s="${s}">▶ Start Workout</button>
      </div>
      ${session.blocks.length
        ? `<ul class="blocks">${session.blocks.map((block, b) => renderBlock(block, w, s, b, session.domain, allowSwap)).join('')}</ul>`
        : emptySession(session)}
      ${renderOmitted(session.omitted)}
      ${session.blockedByGates?.length ? `
        <details class="blocked-gates" style="margin-top:8px;">
          <summary class="note" style="cursor:pointer;">${session.blockedByGates.length} exercise(s) gated by skill/safety</summary>
          <ul class="note" style="margin:4px 0 0; padding-left:18px;">
            ${session.blockedByGates.map((g) => `<li><strong>${esc(g.id)}</strong>: ${esc(g.reason)}</li>`).join('')}
          </ul>
        </details>
      ` : ''}
      <p class="meta">${domainMeta}${timing ? ` · ${timing}` : ''}</p>
    </article>`;
}

function renderBlock(block, w, s, b, domain, allowSwap = true) {
  const type = block.blockType ?? 'straight';
  const heading = type === 'straight'
    ? ''
    : `<div class="block-group-head"><strong>${esc(blockLabel(type))}</strong><span class="tag">${block.setGroups.length} exercises</span></div>`;

  return `
    <li class="block block-${esc(type)}">
      ${heading}
      <ol class="setgroups">
        ${block.setGroups.map((group, g) => renderSetGroup(group, w, s, b, g, domain, type, block.rounds, allowSwap)).join('')}
      </ol>
    </li>`;
}

function renderSetGroup(group, w, s, b, g, domain, blockType, rounds, allowSwap = true) {
  const p = group;
  const role = group.role ? `<span class="tag">${esc(group.role)}</span>` : '';
  const warmup = group.warmupRequired
    ? '<span class="tag warn-tag" title="Perform appropriate warm-up sets before the prescribed work sets">warm-up required</span>'
    : '';
  const marker = blockType === 'straight' ? '' : `<span class="marker">${g + 1}</span>`;
  const swapped = group.swappedFrom
    ? `<p class="note">Swapped from ${esc(group.swappedFrom.name)}</p>`
    : '';

  const controls = domain === 'load'
    ? loadControls(p, w, s, b, g, allowSwap)
    : timeControls(p, w, s, b, g, rounds, allowSwap);

  let warmupHtml = '';
  if (group.warmupRequired) {
    const exObj = currentDefs?.exercises?.find((e) => e.id === group.exerciseId);
    const maxEntry = persisted ? currentMax(persisted, group.exerciseId) : null;
    const ld = getEquipmentLoadDefaults();
    const barWt = barWeightFor(exObj, { unit: ld.unit, barWeights: ld.barWeights });
    const workingWt = (maxEntry?.e1rm > 0 && p.intensityOf1RM != null)
      ? roundToLoadable(maxEntry.e1rm * p.intensityOf1RM, { increment: ld.increment, minWeight: barWt })
      : null;
    const ramp = prescribeWarmup(group, { workingWeight: workingWt, barWeight: barWt, increment: ld.increment, unit: ld.unit });
    if (ramp) {
      warmupHtml = `<p class="note warmup-ramp" style="margin:4px 0 0;">🔥 ${esc(ramp.text)}</p>`;
    }
  }

  // #63. Rendered ONLY where text exists — 99 of 307 rows today. A disclosure
  // on the other 208 would open onto an apology, and the review pass fills them
  // in over time rather than all at once.
  const howto = HAS_INSTRUCTIONS.has(group.exerciseId)
    ? `<details class="howto">
        <summary data-howto="${esc(group.exerciseId)}">How to perform</summary>
        <ol class="howto-steps"><li class="note">Loading…</li></ol>
       </details>`
    : '';

  return `
    <li class="setgroup${group.swappedFrom ? ' swapped' : ''}">
      <div class="block-head">
        ${marker}<strong>${esc(group.name)}</strong>${role}${warmup}
      </div>
      ${controls}
      ${warmupHtml}
      ${swapped}
      ${howto}
    </li>`;
}

function loadControls(p, w, s, b, g, allowSwap = true) {
  // No absolute load until logged maxes exist (M7). Percent-of-1RM is all the
  // engine can honestly prescribe, so there is no load branch to fall back to.
  // #78. An AUTHORED load instruction wins over the derived percentage.
  //
  // A preset states its own load — "50% of 10RM" — and that is a prescription
  // the engine did not compute and must not restate as a percentage of a 1RM
  // nobody supplied. Generated programs never set this field, so their
  // rendering is unchanged.
  const exObj = currentDefs?.exercises?.find((e) => e.id === p.exerciseId);
  const maxEntry = persisted ? currentMax(persisted, p.exerciseId) : null;
  let plateHint = '';
  let load;
  if (p.loadNote) {
    load = p.loadNote;
  } else if (p.intensityOf1RM != null) {
    if (maxEntry?.e1rm > 0) {
      const ld = getEquipmentLoadDefaults();
      const barWt = barWeightFor(exObj, { unit: ld.unit, barWeights: ld.barWeights });
      const rounded = roundToLoadable(maxEntry.e1rm * p.intensityOf1RM, { increment: ld.increment, minWeight: isPlateLoaded(exObj) ? barWt : 0 });
      load = `${rounded} ${ld.unit} (${formatNumber(p.intensityOf1RM * 100)}% 1RM)`;
      if (isPlateLoaded(exObj)) {
        const pm = computePlateLoad(rounded, { barWeight: barWt, plates: ld.plates, unit: ld.unit });
        plateHint = pm.achievable
          ? `<p class="note" style="margin:2px 0 0;">🏋️ ${esc(pm.formatted)}</p>`
          : `<p class="catalog-warn" style="margin:2px 0 0;">⚠️ ${esc(pm.reason)}</p>`;
      }
    } else {
      load = `${formatNumber(p.intensityOf1RM * 100)}% 1RM`;
    }
  } else {
    load = `RIR ${formatNumber(p.rir ?? 2)} (effort target)`;
  }
  const rirLabel = p.intensityOf1RM != null && p.rir != null
    ? `target RIR ${formatNumber(p.rir)}`
    : '';
  const intensity = [load, rirLabel, p.restSeconds != null ? `${p.restSeconds}s rest` : '']
    .filter(Boolean).join(' · ');

  return `
    <div class="block-edit">
      ${numberEdit('sets', p.sets, w, s, b, g, 1)}
      ${numberEdit('reps', p.reps, w, s, b, g, 1)}
      <p class="intensity">${esc(intensity)}</p>
      ${plateHint}
      ${editActions(w, s, b, g, allowSwap)}
    </div>`;
}

function timeControls(p, w, s, b, g, rounds, allowSwap = true) {
  const details = [
    p.workSeconds != null ? `${p.workSeconds}s work` : '',
    p.restSeconds != null ? `${p.restSeconds}s rest` : '',
    rounds != null ? `${rounds} rounds` : ''
  ].filter(Boolean).join(' · ');

  return `
    <div class="block-edit">
      ${p.workSeconds != null ? numberEdit('workSeconds', p.workSeconds, w, s, b, g, 1, 'work (sec)') : ''}
      ${p.restSeconds != null ? numberEdit('restSeconds', p.restSeconds, w, s, b, g, 1, 'rest (sec)') : ''}
      <p class="intensity">${esc(details || 'timed prescription')}</p>
      ${editActions(w, s, b, g, allowSwap)}
    </div>`;
}

